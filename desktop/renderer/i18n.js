const DEFAULT_LANG = 'ru';

function getLang() {
  try {
    return localStorage.getItem('uiLanguage') || DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

/** Looks up a key for the current language, falling back to Russian, then the key itself. Supports {placeholders}. */
function t(key, vars) {
  const lang = getLang();
  let text = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) ?? TRANSLATIONS[DEFAULT_LANG][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v);
  }
  return text;
}

function setLang(lang) {
  try {
    localStorage.setItem('uiLanguage', lang);
  } catch {
    // Private window / storage disabled - language just won't stick across restarts.
  }
}

/** Applies every [data-i18n]/[data-i18n-html]/[data-i18n-placeholder]/[data-i18n-title] in the document. */
function applyStaticTranslations() {
  document.documentElement.lang = getLang();
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
}
